import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('ps-radar/preview-v2/index.html','utf8');
const code=html.slice(html.indexOf('function alertSignals'),html.indexOf('function saveAlerts'));
const signals=vm.runInNewContext(code+';alertSignals');
const now=Date.parse('2026-10-04T00:00:00Z');
const g={currentPrice:30000,discountPercent:50,fetchedAt:'2026-10-04T00:00:00Z',saleEndsAt:'2026-10-04T23:00:00Z'};
const rule={enabled:true,target:35000,low:true,start:true,end:true,threshold:50};
const prior={price:60000,discount:0,low:40000,target:35000,threshold:50};
const types=(g,r,p)=>Array.from(signals(g,r,p,now),x=>x.type);
assert.deepEqual(types(g,rule,prior),['target','low','start','threshold','end']);
assert.deepEqual(types({...g,saleEndsAt:null},rule,{...prior,price:30000,discount:50,low:30000}),[]);
for(const patch of [{upcoming:true},{priceNeedsVerification:true},{currentPrice:0},{priceStatus:'rejected-outlier'}])assert.deepEqual(types({...g,...patch},rule,prior),[]);
assert.deepEqual(types(g,{...rule,enabled:false},prior),[]);
assert(!types({...g,saleEndsAt:'2026-10-03T00:00:00Z'},rule,prior).includes('end'));
assert(!types(g,rule,null).includes('start'));
assert(types({...g,discountPercent:70},{...rule,threshold:70},{...prior,discount:50,threshold:70}).includes('threshold'));
console.log('PASS: five alert conditions and repeat, stale, initial-sale, invalid-price guards');
